#include "bsp_sys.h"

void bsp_cache_enable(void)
{
    // 使能 I-Cache / D-Cache，以提升CPU访问速度。
    // 对外部存储器（如FMC SDRAM）尤其需要配合 MPU/Cache属性设置：
    // 否则可能出现“CPU读的是缓存旧数据”或“写入未按预期回写”的一致性问题。
    SCB_EnableICache();
    SCB_EnableDCache();
    // 设定 Cache 行为位：通常用于开启/调整写回等策略（此处保留原工程写法）
    SCB->CACR |= 1U << 2;
}
